const orderedVerbs = Object.keys(verbs).sort(
  (a, b) => b.length - a.length,
) as (keyof typeof verbs)[];
export function localizeBuiltinToolLabel(text: string, t: UiTranslator): string {
  for (const [prefix, key] of [
    ["Failed to ", "workLogExtra.failed"],
    ["Declined to ", "workLogExtra.declined"],
    ["Stopped ", "workLogExtra.stopped"],
  ] as const) {
    if (!text.startsWith(prefix)) continue;
    const rest = text.slice(prefix.length);
    const verb = orderedVerbs.find((value) => rest.startsWith(`${value.toLowerCase()} `));
    if (verb) {
      const label = localizeBuiltinToolLabel(`${verb}${rest.slice(verb.length)}`, t);
      return t(key, { label: label.charAt(0).toLowerCase() + label.slice(1) });
    }
  }
  for (const verb of orderedVerbs) {
    if (!text.startsWith(`${verb} `)) continue;
    const target = text.slice(verb.length + 1);
    const key = Object.hasOwn(objects, target)
      ? objects[target as keyof typeof objects]
      : undefined;
    return t(verbs[verb], { target: key ? t(key) : target });
  }
  return text;
}
